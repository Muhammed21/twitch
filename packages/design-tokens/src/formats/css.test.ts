import { describe, expect, it } from "vitest";

import { formatCssVariables } from "./css.ts";
import type { DesignToken } from "./swift.ts";

const token = (path: readonly string[], $type: string, value: unknown): DesignToken => ({
  path,
  $type,
  value,
});

const themes = {
  light: [
    token(["color", "background", "primary"], "color", "#f7f7f8"),
    token(["color", "accent", "onAccentStrong"], "color", "#000000"),
  ],
  dark: [
    token(["color", "background", "primary"], "color", "#0e0e10"),
    token(["color", "accent", "onAccentStrong"], "color", "#000000"),
  ],
};

const shared = [
  token(["spacing", "x16"], "dimension", "16px"),
  token(["radius", "lg"], "dimension", "6px"),
  token(["typography", "displayText"], "iosTextStyle", { textStyle: "headline", fontWeight: 600 }),
  token(["typography", "heroText"], "iosTextStyle", { textStyle: "largeTitle", fontWeight: 700 }),
];

describe("sortie CSS des tokens (ADR 0019, ADR 0039)", () => {
  it("écrit le thème clair dans :root et le thème sombre sous prefers-color-scheme: dark", () => {
    expect(formatCssVariables({ themes, shared })).toBe(
      [
        "/* Generated by @repo/design-tokens — do not edit. */",
        "/* Source: packages/design-tokens/tokens/** */",
        "",
        ":root {",
        "  --color-background-primary: #f7f7f8;",
        "  --color-accent-on-accent-strong: #000000;",
        "  --spacing-x16: 16px;",
        "  --radius-lg: 6px;",
        "  --typography-display-text-font: -apple-system-headline;",
        "  --typography-display-text-weight: 600;",
        "  --typography-hero-text-font: -apple-system-title0;",
        "  --typography-hero-text-weight: 700;",
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
        "    --color-background-primary: #0e0e10;",
        "    --color-accent-on-accent-strong: #000000;",
        "  }",
        "}",
        "",
      ].join("\n"),
    );
  });

  it.each([
    ["subheadline", "-apple-system-subheadline"],
    ["footnote", "-apple-system-footnote"],
    ["body", "-apple-system-body"],
  ])("traduit le style iOS %s en police système de Safari %s", (textStyle, font) => {
    const css = formatCssVariables({
      themes: { light: [], dark: [] },
      shared: [token(["typography", "x"], "iosTextStyle", { textStyle, fontWeight: 400 })],
    });

    expect(css).toContain(`  --typography-x-font: ${font};`);
  });

  it("refuse un style iOS sans équivalent dans Safari", () => {
    expect(() =>
      formatCssVariables({
        themes: { light: [], dark: [] },
        shared: [
          token(["typography", "x"], "iosTextStyle", { textStyle: "caption9", fontWeight: 400 }),
        ],
      }),
    ).toThrow(
      'Token "typography.x" uses the iOS text style "caption9", which has no Safari system font.',
    );
  });

  it.each([null, "headline", 600, {}, { fontWeight: 600 }, { textStyle: 1, fontWeight: 600 }])(
    "refuse un style de texte mal formé %j",
    (value) => {
      expect(() =>
        formatCssVariables({
          themes: { light: [], dark: [] },
          shared: [token(["typography", "x"], "iosTextStyle", value)],
        }),
      ).toThrow('Token "typography.x" is not an iOS text style value.');
    },
  );

  it("n'écrit pas de graisse quand le style n'en donne pas", () => {
    const css = formatCssVariables({
      themes: { light: [], dark: [] },
      shared: [token(["typography", "x"], "iosTextStyle", { textStyle: "body" })],
    });

    expect(css).toContain("  --typography-x-font: -apple-system-body;\n}");
  });

  it("écrit telle quelle la valeur d'un token qui n'est pas un style de texte", () => {
    const css = formatCssVariables({
      themes: { light: [], dark: [] },
      shared: [token(["radius", "pill"], "dimension", "9999px")],
    });

    expect(css).toContain("  --radius-pill: 9999px;\n}");
  });
});
